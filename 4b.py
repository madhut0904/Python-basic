#membership operators
a = [1,2,3,4,5]
print(1 in a)
print(6 in a)
print(1 not in a)
print(6 not in a)
x="hello"
print("h" in x)
print("z" in x)


#bitwise operators
a = 10
b = 4
print(a & b)
print(a | b)
print(a ^ b)
print(~a)
print(a << 2)
print(a >> 2)