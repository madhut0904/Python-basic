#operators
#logical operators
print(True and False)
print(True or False)
print(not(True))
print(not(False))
print(not(1))
print(not(0))
print(not(-1))
print(True and True)
print(True or True)
print(False and False)
print(False or False)

print(1>2)
print(1<2)
print(1>2 and 2>1)
